"""Project's Models."""
import uuid
from typing import List
from pydantic import BaseModel, Field


class MinimalSource(BaseModel):
    """Represents a source location in the codebase.

    Attributes:
        file_path: Path to the source file.
        first_character_index: Starting character index of the fragment.
        last_character_index: Ending character index of the fragment.
    """

    file_path: str
    first_character_index: int
    last_character_index: int


class UnansweredQuestion(BaseModel):
    """Represents a question without an answer.

    Attributes:
        question_id: Unique identifier of the question.
        question: Question text.
    """

    question_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    question: str


class AnsweredQuestion(UnansweredQuestion):
    """Represents a question with an answer and sources.

    Attributes:
        sources: Source locations containing the answer.
        answer: Expected answer to the question.
    """

    sources: List[MinimalSource]
    answer: str


class RagDataset(BaseModel):
    """Represents a dataset of RAG questions.

    Attributes:
        rag_questions: Collection of answered or unanswered questions.
    """

    rag_questions: List[AnsweredQuestion | UnansweredQuestion]


class MinimalSearchResults(BaseModel):
    """Represents search results for a single question.

    Attributes:
        question_id: Unique identifier of the question.
        question: Question text.
        retrieved_sources: Retrieved source locations.
    """

    question_id: str
    question: str
    retrieved_sources: List[MinimalSource]


class MinimalAnswer(MinimalSearchResults):
    """Represents search results with a generated answer.

    Attributes:
        answer: Answer generated by the language model.
    """

    answer: str


class StudentSearchResults(BaseModel):
    """Represents all search results from the student system.

    Attributes:
        search_results: Retrieval results for all questions.
        k: Number of retrieved sources per question.
    """

    search_results: List[MinimalSearchResults]
    k: int


class StudentSearchResultsAndAnswer(BaseModel):
    """Represents all search results with generated answers.

    Attributes:
        search_results: Generated answers and their retrieved sources.
        k: Number of retrieved sources used for each answer.
    """

    search_results: List[MinimalAnswer]
    k: int


class Chunk(BaseModel):
    """Represents a chunk of text from a file.

    Attributes:
        file_path: Path to the file containing the chunk.
        content: Text content of the chunk.
        first_character_index: Starting character index of the chunk.
        last_character_index: Ending character index of the chunk.
        chunk_type: Type of the chunk (for example, "python" or "text").
    """

    file_path: str
    content: str
    first_character_index: int
    last_character_index: int
    chunk_type: str = "text"
